export function getTranslation(key: string, lang: SupportedLanguageCode): string {
  if (!key) return '';

  // 1. Direct key match in TRANSLATIONS dictionary
  if (TRANSLATIONS[key] && TRANSLATIONS[key][lang]) {
    return TRANSLATIONS[key][lang];
  }

  // 2. Phrase-to-key normalizer lookup (e.g. 'Inventory & Operations' -> 'inventoryOperations')
  const normalized = key.toLowerCase().trim();
  if (PHRASE_TO_KEY[normalized]) {
    const mappedKey = PHRASE_TO_KEY[normalized];
    if (TRANSLATIONS[mappedKey] && TRANSLATIONS[mappedKey][lang]) {
      return TRANSLATIONS[mappedKey][lang];
    }
  }

  // 3. Check dotted key path in locales JSON schema (e.g. 'nav.home' or 'forms.fullNameLabel')
  if (key.includes('.')) {
    const res = getLocaleString(lang, key);
    if (res !== key) return res;
  }

  // 4. Check common namespaces in JSON locales
  const commonPrefixes = ['nav', 'header', 'welcome', 'dashboard', 'forms', 'badges', 'footer', 'metadata'];
  for (const prefix of commonPrefixes) {
    const res = getLocaleString(lang, `${prefix}.${key}`);
    if (res !== `${prefix}.${key}`) {
      return res;
    }
  }

  // Fallback to English translation if available, or original key
  if (TRANSLATIONS[key] && TRANSLATIONS[key]['en']) {
    return TRANSLATIONS[key]['en'];
  }
  return key;
}
