export function getTranslation(key: string, lang: SupportedLanguageCode): string {
  // Check if it's a dotted key path in our rich schema (e.g. 'nav.getStarted' or 'forms.fullNameLabel')
  if (key.includes('.')) {
    const res = getLocaleString(lang, key);
    if (res !== key) return res;
  }

  // Check flat keys in TRANSLATIONS dictionary
  if (TRANSLATIONS[key]) {
    if (TRANSLATIONS[key][lang]) {
      return TRANSLATIONS[key][lang];
    }
    return TRANSLATIONS[key]['en'] || key;
  }

  // Check if the key maps to common namespaces in JSON locales
  const commonPrefixes = ['nav', 'header', 'welcome', 'dashboard', 'forms', 'badges', 'footer', 'metadata'];
  for (const prefix of commonPrefixes) {
    const res = getLocaleString(lang, `${prefix}.${key}`);
    if (res !== `${prefix}.${key}`) {
      return res;
    }
  }

  return key;
}
